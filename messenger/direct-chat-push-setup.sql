-- Direct recipient messaging + per-device web push subscriptions
-- Run in Supabase SQL Editor AFTER the existing secure-setup.sql.

alter table public.messages
  add column if not exists receiver_id uuid references auth.users(id) on delete set null;

create index if not exists messages_room_receiver_created_idx
  on public.messages(room_id, receiver_id, created_at);

drop policy if exists "members read messages" on public.messages;
create policy "participants read direct messages" on public.messages
for select to authenticated using (
  public.is_room_member(room_id)
  and (receiver_id is null or sender_id = (select auth.uid()) or receiver_id = (select auth.uid()))
);

drop policy if exists "members send messages as self" on public.messages;
create policy "members send direct messages as self" on public.messages
for insert to authenticated with check (
  sender_id = (select auth.uid())
  and public.is_room_member(room_id)
  and (receiver_id is null or exists (
    select 1 from public.room_members target
    where target.room_id = messages.room_id and target.user_id = messages.receiver_id
  ))
);

create table if not exists public.push_subscriptions (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  endpoint text not null unique,
  subscription jsonb not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
alter table public.push_subscriptions enable row level security;
drop policy if exists "users manage own push subscriptions" on public.push_subscriptions;
create policy "users manage own push subscriptions" on public.push_subscriptions
for all to authenticated using (user_id = (select auth.uid()))
with check (user_id = (select auth.uid()));
grant select, insert, update, delete on public.push_subscriptions to authenticated;
grant usage, select on sequence public.push_subscriptions_id_seq to authenticated;

-- Push delivery requires a deployed Supabase Edge Function with VAPID secrets.
-- Never place the VAPID private key or service-role key in browser code.

-- Realtime roster updates so newly joined customers appear in the recipient list.
do $$
begin
  if not exists (
    select 1 from pg_publication_tables
    where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'room_members'
  ) then
    alter publication supabase_realtime add table public.room_members;
  end if;
end $$;
