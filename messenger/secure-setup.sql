-- Kamrul Eagle Prime Messenger: room-scoped RLS + private media
-- Run this whole file in Supabase Dashboard > SQL Editor > New query.
-- Also enable Authentication > Providers > Anonymous sign-ins.

create extension if not exists pgcrypto;

create table if not exists public.rooms (
  id uuid primary key default gen_random_uuid(),
  owner_id uuid not null references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

create table if not exists public.room_members (
  room_id uuid not null references public.rooms(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  display_name text not null default 'Guest' check (char_length(display_name) between 1 and 40),
  joined_at timestamptz not null default now(),
  primary key (room_id, user_id)
);

create table if not exists public.messages (
  id bigint generated by default as identity primary key,
  room_id uuid not null references public.rooms(id) on delete cascade,
  sender_id uuid not null references auth.users(id) on delete cascade,
  sender text not null check (char_length(sender) between 1 and 40),
  body text not null check (char_length(body) <= 4000),
  kind text not null default 'text' check (kind in ('text','image','video','audio','location')),
  created_at timestamptz not null default now()
);
create index if not exists messages_room_created_idx on public.messages(room_id, created_at);

create table if not exists public.call_signals (
  id bigint generated by default as identity primary key,
  room_id uuid not null references public.rooms(id) on delete cascade,
  sender_id uuid not null references auth.users(id) on delete cascade,
  sender text not null check (char_length(sender) between 1 and 40),
  payload jsonb not null,
  created_at timestamptz not null default now()
);
create index if not exists call_signals_room_created_idx on public.call_signals(room_id, created_at);

create or replace function public.is_room_member(p_room_id uuid)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.room_members rm
    where rm.room_id = p_room_id and rm.user_id = (select auth.uid())
  );
$$;
revoke all on function public.is_room_member(uuid) from public;
grant execute on function public.is_room_member(uuid) to anon, authenticated;

alter table public.rooms enable row level security;
alter table public.room_members enable row level security;
alter table public.messages enable row level security;
alter table public.call_signals enable row level security;

drop policy if exists "room owners create rooms" on public.rooms;
create policy "room owners create rooms" on public.rooms
for insert to authenticated with check (owner_id = (select auth.uid()));
drop policy if exists "members read rooms" on public.rooms;
create policy "members read rooms" on public.rooms
for select to authenticated using (public.is_room_member(id));

drop policy if exists "members read roster" on public.room_members;
create policy "members read roster" on public.room_members
for select to authenticated using (public.is_room_member(room_id) or user_id = (select auth.uid()));
drop policy if exists "users join rooms by invite" on public.room_members;
create policy "users join rooms by invite" on public.room_members
for insert to authenticated with check (user_id = (select auth.uid()));
drop policy if exists "users update own membership name" on public.room_members;
create policy "users update own membership name" on public.room_members
for update to authenticated using (user_id = (select auth.uid()))
with check (user_id = (select auth.uid()));

drop policy if exists "members read messages" on public.messages;
create policy "members read messages" on public.messages
for select to authenticated using (public.is_room_member(room_id));
drop policy if exists "members send messages as self" on public.messages;
create policy "members send messages as self" on public.messages
for insert to authenticated with check (
  sender_id = (select auth.uid()) and public.is_room_member(room_id)
);

drop policy if exists "members read call signals" on public.call_signals;
create policy "members read call signals" on public.call_signals
for select to authenticated using (public.is_room_member(room_id));
drop policy if exists "members send call signals as self" on public.call_signals;
create policy "members send call signals as self" on public.call_signals
for insert to authenticated with check (
  sender_id = (select auth.uid()) and public.is_room_member(room_id)
);

-- Private Storage bucket. Media objects are stored under: <room-uuid>/<filename>
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('chat-media', 'chat-media', false, 26214400,
        array['image/jpeg','image/png','image/webp','image/gif','video/mp4','video/webm','audio/webm','audio/ogg','audio/mp4'])
on conflict (id) do update set public = false, file_size_limit = 26214400;

drop policy if exists "room members read media" on storage.objects;
create policy "room members read media" on storage.objects
for select to authenticated using (
  bucket_id = 'chat-media'
  and (storage.foldername(name))[1] ~* '^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$'
  and public.is_room_member(((storage.foldername(name))[1])::uuid)
);
drop policy if exists "room members upload media" on storage.objects;
create policy "room members upload media" on storage.objects
for insert to authenticated with check (
  bucket_id = 'chat-media'
  and (storage.foldername(name))[1] ~* '^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$'
  and public.is_room_member(((storage.foldername(name))[1])::uuid)
);

-- Enable Realtime publication for live messages and call signaling.
do $$
begin
  if not exists (
    select 1 from pg_publication_tables
    where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'messages'
  ) then
    alter publication supabase_realtime add table public.messages;
  end if;
  if not exists (
    select 1 from pg_publication_tables
    where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'call_signals'
  ) then
    alter publication supabase_realtime add table public.call_signals;
  end if;
end $$;

